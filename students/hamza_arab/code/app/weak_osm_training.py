"""Hands-free *experimental* OSM weak supervision for hospital-roof candidates.

NO human-verified labels are created or changed. A weak model can learn from
geographically aligned building polygons with OSM hospital evidence, but OSM
labels are NOT independent ground truth. Proxy metrics are NEVER real-world
hospital detection accuracy. Results never overwrite the reviewed detector.
"""
from __future__ import annotations

import hashlib
import json
import math
import random
import shutil
from collections import Counter
from pathlib import Path

import pandas as pd
import yaml
from PIL import Image


def sha(path):
    h=hashlib.sha256()
    with open(path,'rb') as f:
        for b in iter(lambda:f.read(1024*1024),b''):h.update(b)
    return h.hexdigest()


def box_to_yolo(box,w,h):
    if not isinstance(box,(list,tuple)) or len(box)!=4 or w<=0 or h<=0:raise ValueError('Invalid box or image size')
    x1,y1,x2,y2=[float(n) for n in box]
    if not all(math.isfinite(v) for v in [x1,y1,x2,y2]):raise ValueError('Nonfinite box')
    x1=max(0,min(w,x1)); x2=max(0,min(w,x2))
    y1=max(0,min(h,y1)); y2=max(0,min(h,y2))
    if x2-x1<6 or y2-y1<6:raise ValueError('Too-small box')
    return f'0 {(x1+x2)/(2*w):.7f} {(y1+y2)/(2*h):.7f} {(x2-x1)/w:.7f} {(y2-y1)/h:.7f}'


def make_weak_dataset(root, *, min_evidence=2, minimum_sites=8, seed=4008):
    """Convert only OSM draft roof boxes to isolated pseudo-label YOLO dataset.

    min_evidence 3: explicit amenity/healthcare=hospital on building.
    min_evidence 2: additionally building=hospital (could be repurposed).
    min_evidence 1: additionally buildings inside hospital campus (higher risk).
    No generic distance-only evidence 0 is included. Site-wise train/val/test.
    """
    root=Path(root).resolve(); manifest=root/'review_manifest.csv'
    if min_evidence not in (1,2,3):raise ValueError('min_evidence must be 1,2,3')
    if not 6<=minimum_sites<=100:raise ValueError('minimum_sites must be 6..100')
    if not manifest.is_file():raise FileNotFoundError('Missing review_manifest.csv')
    df=pd.read_csv(manifest,keep_default_na=False)
    required={'tile_id','site_id','image','geotiff','candidate_class','review_status','imagery_license_url'}
    if not required.issubset(df):raise ValueError('Manifest missing fields: '+str(sorted(required-set(df))))
    if df.tile_id.duplicated().any():raise ValueError('Duplicate tile IDs')
    records=[];counts=Counter()
    for _,r in df.iterrows():
        # preserve and exclude human-reviewed data; no autogenerated ground truth.
        if r.review_status!='UNREVIEWED' or r.candidate_class!='known_hospital_site':continue
        tile=str(r.tile_id)
        if '/' in tile or '..' in tile:continue
        ann=root/'drafts'/'osm'/(tile+'.json')
        ov=root/'drafts'/'overture'/(tile+'.json')
        # Prefer a usable OSM candidate. A cached empty/near-reference-only OSM
        # draft must not prevent legitimate Overture data from being considered.
        try:
            osm_doc=json.loads(ann.read_text(encoding='utf-8')) if ann.is_file() else {}
            usable_osm=any(int(c.get('evidence_level',-1))>=min_evidence for c in osm_doc.get('candidates',[]))
        except (ValueError,OSError,TypeError):
            usable_osm=False
        if (not usable_osm) and ov.is_file():
            ann=ov
        if not ann.is_file():counts['no_map_draft']+=1;continue
        try:
            doc=json.loads(ann.read_text(encoding='utf-8'))
            if doc.get('tile_id')!=tile or doc.get('approved') is not False:raise ValueError('Unacceptable draft status')
            image=(root/str(r.image)).resolve(); tif=(root/str(r.geotiff)).resolve()
            if not image.is_relative_to(root) or not tif.is_relative_to(root) or not image.is_file() or not tif.is_file():
                raise ValueError('Image/GeoTIFF missing or outside root')
            with Image.open(image) as picture:width,height=picture.size
            lines=[];evidence=[];ids=set()
            for c in doc.get('candidates',[]):
                lvl=int(c.get('evidence_level',-1))
                if not min_evidence<=lvl<=3:continue
                if lvl==3 and c.get('reason')!='explicit_hospital_use_tag':continue
                if lvl==2 and c.get('reason') not in ('building_hospital_tag_not_confirmed_current_use','overture_building_class_hospital'):continue
                if lvl==1 and c.get('reason') not in ('building_inside_mapped_hospital_campus','overture_nearest_footprint_to_odhf_reference_only'):continue
                osm_id=str(c.get('osm_id',''))
                if not (osm_id.startswith('way/') or osm_id.startswith('relation/') or osm_id.startswith('overture/')) or osm_id in ids:continue
                ids.add(osm_id)
                lines.append(box_to_yolo(c['bbox'],width,height));evidence.append({'osm_id':osm_id,'evidence_level':lvl,'reason':c.get('reason','')})
            if not lines:counts['no_strong_roof_evidence']+=1;continue
            if not str(r.imagery_license_url).startswith('https://'):raise ValueError('Missing recorded imagery source license URL')
            records.append({'tile_id':tile,'site_id':str(r.site_id),'image':image,'lines':lines,
                            'evidence':evidence,'draft_source':str(doc.get('source','unknown')),'imagery_source':str(r.get('imagery_source','')),
                            'imagery_license_url':str(r.imagery_license_url),'draft_path':ann})
            counts['matched_images']+=1
        except (ValueError,TypeError,KeyError,OSError,json.JSONDecodeError) as exc:
            counts['invalid_record']+=1
            continue
    groups={}
    for r in records:groups.setdefault(r['site_id'],[]).append(r)
    if len(groups)<minimum_sites:
        summary={'status':'INSUFFICIENT_PSEUDO_LABEL_SITES','candidate_images':int(len(df)),'matched_images':len(records),
                 'independent_sites':len(groups),'minimum_sites':minimum_sites,'minimum_evidence':min_evidence,
                 'counts':dict(counts),'training_started':False,
                 'next':'Need more explicitly mapped hospital building footprints; do not automatically label OSM grounds or make up training labels.'}
        p=root/'weak_osm_experiment'/'preparation_status.json';p.parent.mkdir(parents=True,exist_ok=True)
        p.write_text(json.dumps(summary,indent=2))
        return summary
    rng=random.Random(seed);sids=sorted(groups);rng.shuffle(sids)
    n=len(sids);n_test=max(2,int(n*.2));n_val=max(2,int(n*.2));
    if n-n_test-n_val<2:raise ValueError('Not enough training groups')
    by_site={sid:('test' if i<n_test else 'val' if i<n_test+n_val else 'train') for i,sid in enumerate(sids)}
    dest=root/'weak_osm_experiment'/'dataset';dest.mkdir(parents=True,exist_ok=True)
    # refresh only this isolated weak dataset; never touch verified label files.
    for fold in ['images','labels']:
        shutil.rmtree(dest/fold,ignore_errors=True)
    rows=[]
    for r in records:
        split=by_site[r['site_id']]
        img=dest/'images'/split/r['image'].name
        lbl=dest/'labels'/split/(r['image'].stem+'.txt')
        img.parent.mkdir(parents=True,exist_ok=True);lbl.parent.mkdir(parents=True,exist_ok=True)
        shutil.copy2(r['image'],img);lbl.write_text('\n'.join(r['lines'])+'\n',encoding='utf-8')
        rows.append({'site_id':r['site_id'],'tile_id':r['tile_id'],'split':split,'num_pseudo_boxes':len(r['lines']),
                     'map_evidence':json.dumps(r['evidence'],separators=(',',':')),'draft_source':r['draft_source'],
                     'image_sha256':sha(img),'osm_draft_sha256':sha(r['draft_path']),
                     'imagery_source':r['imagery_source'],'imagery_license_url':r['imagery_license_url']})
    data={'path':str(dest),'train':'images/train','val':'images/val','test':'images/test','names':{0:'hospital_candidate'}}
    (dest/'data.yaml').write_text(yaml.safe_dump(data,sort_keys=False))
    csv=dest/'weak_site_split_manifest.csv';pd.DataFrame(rows).to_csv(csv,index=False)
    summary={'status':'WEAK_PSEUDO_DATASET_READY_NOT_GROUND_TRUTH','independent_sites':n,
        'matched_images':len(records),'pseudo_boxes':sum(len(r['lines']) for r in records),
        'train_sites':sum(v=='train' for v in by_site.values()),
        'val_sites':sum(v=='val' for v in by_site.values()),'test_sites':sum(v=='test' for v in by_site.values()),
        'minimum_evidence':min_evidence,'manifest_sha256':sha(csv),'data_yaml':str(dest/'data.yaml'),
        'counts':dict(counts),'training_started':False,
        'disclaimer':'Training labels come from OSM or Overture building polygons and ODHF reference proximity, NEVER independent hospital identity verification. Metrics are map-derived proxy only, not real accuracy.'}
    (dest.parent/'preparation_status.json').write_text(json.dumps(summary,indent=2))
    return summary


def train_weak_experiment(root,*,epochs=12,batch=8,imgsz=640,pretrained='yolo11n.pt'):
    """GPU train against OSM pseudo labels. Reports PROXY metrics only."""
    root=Path(root);experiment=root/'weak_osm_experiment';info=json.loads((experiment/'preparation_status.json').read_text())
    if info.get('status')!='WEAK_PSEUDO_DATASET_READY_NOT_GROUND_TRUTH':
        raise ValueError('Not enough OSM pseudo labels; no experimental training permitted')
    if not 1<=epochs<=100 or not 1<=batch<=64:raise ValueError('Invalid training options')
    if not (experiment/'dataset'/'weak_site_split_manifest.csv').exists():raise ValueError('Missing split')
    if sha(experiment/'dataset'/'weak_site_split_manifest.csv')!=info['manifest_sha256']:
        raise ValueError('Weak dataset changed since preparation')
    from ultralytics import YOLO
    import torch
    model=YOLO(pretrained)
    if not torch.cuda.is_available():
        raise RuntimeError('GPU not available: in Notebook 08 select Runtime > Change runtime type > T4 GPU before starting training. No slow CPU training attempted.')
    device=0
    fit=model.train(data=info['data_yaml'],epochs=epochs,imgsz=imgsz,batch=batch,
        device=device,seed=4008,project=str(experiment/'runs'),name='weak_hospital',exist_ok=True,patience=6)
    weights=Path(fit.save_dir)/'weights'/'best.pt'
    if not weights.is_file():raise RuntimeError('No weights after YOLO training')
    out=experiment/'weak_best.pt';shutil.copy2(weights,out)
    ev=YOLO(str(out)).val(data=info['data_yaml'],split='test',imgsz=imgsz,device=device,
                             project=str(experiment/'runs'),name='weak_test',exist_ok=True)
    vals={'precision_proxy':float(ev.box.mp),'recall_proxy':float(ev.box.mr),
          'mAP50_proxy':float(ev.box.map50),'mAP50_95_proxy':float(ev.box.map)}
    if not all(math.isfinite(v) and 0<=v<=1 for v in vals.values()):raise ValueError('Invalid weak-label metrics')
    report={'status':'TRAINED_ON_OSM_PSEUDO_LABELS_NOT_VERIFIED', 'weights_sha256':sha(out),
        'split_sha256':info['manifest_sha256'],'training_image_count':info['matched_images'],
        'proxy_test_sites':info['test_sites'],'model_weights':str(out),
        'proxy_metrics':vals,'model_input':pretrained,'epochs':epochs,'device':str(device),
        'disclaimer':'Measured only against independent-site OSM/Overture/ODHF weak pseudo-labels. No hospital identification accuracy claim.'}
    (experiment/'weak_training_report.json').write_text(json.dumps(report,indent=2))
    return report


def export_weak_heldout_geojson(root, *, conf=0.35, max_images=30):
    """Genuine model-inferred WGS84 points, clearly classified as WEAK/UNVERIFIED.

    Never writes reviewed-detector artifacts or training_report.json. Its model
    uses OSM pseudo labels and has not been evaluated on independent truth.
    """
    root=Path(root).resolve();exp=root/'weak_osm_experiment'
    rep=json.loads((exp/'weak_training_report.json').read_text(encoding='utf-8'))
    weights=exp/'weak_best.pt';split_file=exp/'dataset/weak_site_split_manifest.csv'
    if rep.get('status')!='TRAINED_ON_OSM_PSEUDO_LABELS_NOT_VERIFIED' or not weights.is_file() or not split_file.is_file():
        raise ValueError('No trained OSM weak model')
    if sha(weights)!=rep.get('weights_sha256') or sha(split_file)!=rep.get('split_sha256'):
        raise ValueError('Weak model or dataset changed: inference blocked')
    if not 0<conf<1 or not 1<=max_images<=100:raise ValueError('Invalid inference settings')
    from ultralytics import YOLO
    import rasterio
    from rasterio.transform import xy
    from pyproj import Transformer
    model=YOLO(str(weights))
    man=pd.read_csv(root/'review_manifest.csv',keep_default_na=False)
    splits=pd.read_csv(split_file,keep_default_na=False)
    test=splits.loc[splits.split.eq('test'),['tile_id','site_id']]
    if test.empty:raise ValueError('No held-out pseudo-label images')
    chosen=test.merge(man[['tile_id','site_id','geotiff']],on=['tile_id','site_id'],validate='one_to_one')
    features=[];processed=0
    for _,row in chosen.head(max_images).iterrows():
        path=(root/str(row.geotiff)).resolve()
        if not path.is_relative_to(root) or not path.is_file():raise ValueError('Unsafe or missing GeoTIFF')
        with rasterio.open(path) as ds:
            if not ds.crs or ds.count<3 or ds.dtypes[0]!='uint8':raise ValueError('GeoTIFF unsuitable')
            arr=ds.read((1,2,3)).transpose(1,2,0)
            from_raster=Transformer.from_crs(ds.crs,'EPSG:4326',always_xy=True)
            prediction=model.predict(source=Image.fromarray(arr),conf=conf,verbose=False)
            for result in prediction:
                for b in result.boxes:
                    if int(b.cls[0])!=0:continue
                    x1,y1,x2,y2=[float(z) for z in b.xyxy[0].tolist()]
                    if not all(math.isfinite(z) for z in (x1,x2,y1,y2)) or x2<=x1 or y2<=y1:continue
                    score=float(b.conf[0])
                    if not 0<=score<=1:continue
                    lon,lat=from_raster.transform(*xy(ds.transform,(y1+y2)/2,(x1+x2)/2))
                    if not -142<=lon<=-52 or not 41<=lat<=84:continue
                    features.append({'type':'Feature','geometry':{'type':'Point','coordinates':[lon,lat]},
                        'properties':{'confidence':score,'method':'osm_weak_supervision_experimental',
                        'weights_sha256':rep['weights_sha256'],'test_site_id':str(row.site_id),
                        'warning':'Unverified AI output from OSM pseudo labels, NOT verified hospital identity'}})
                    if len(features)>3000:raise ValueError('Too many map features')
            processed+=1
    geo={'type':'FeatureCollection','features':features,'properties':{
        'status':'UNVERIFIED_WEAKLY_SUPERVISED_MODEL',
        'warning':'Open-map-derived pseudo labels; proxy evaluation cannot establish real hospital detection accuracy.',
        'weights_sha256':rep['weights_sha256'],'image_count':processed}}
    outfile=exp/'experimental_unverified_predictions.geojson'
    temp=outfile.with_suffix('.tmp')
    temp.write_text(json.dumps(geo,indent=2),encoding='utf-8');temp.replace(outfile)
    return {'status':'EXPERIMENTAL_UNVERIFIED_AI_OUTPUT','images':processed,'predictions':len(features),
            'geojson':str(outfile),'warning':geo['properties']['warning']}


def infer_weak_in_selected_circle(root, latitude, longitude, radius_m, *, confidence=.35):
    """Experimental REAL model inference only; hospital use never verified.

    Drawn circle must be 20..250m inside Ontario with licensed image access.
    This path cannot be mistaken for separately evaluated `hospital_ai`.
    """
    from tempfile import TemporaryDirectory
    from importlib import util
    from math import radians, cos, hypot, asin, sin, sqrt
    from pyproj import Transformer
    import rasterio
    from rasterio.transform import xy
    from PIL import Image
    from ultralytics import YOLO
    root=Path(root).resolve()
    exp=root/'weak_osm_experiment'
    report_file=exp/'weak_training_report.json'
    weights=exp/'weak_best.pt'
    split=exp/'dataset/weak_site_split_manifest.csv'
    if not all(p.is_file() for p in (report_file,weights,split)):
        raise RuntimeError('NO EXPERIMENTAL MODEL: training was not completed in Notebook 08')
    report=json.loads(report_file.read_text())
    if (report.get('status')!='TRAINED_ON_OSM_PSEUDO_LABELS_NOT_VERIFIED'
        or report.get('weights_sha256')!=sha(weights)
        or report.get('split_sha256')!=sha(split)):
        raise RuntimeError('Experimental checkpoint provenance mismatch')
    lat,lon,rad=float(latitude),float(longitude),float(radius_m)
    if not (41.7<=lat<=57 and -95.2<=lon<=-73.8 and 20<=rad<=250 and 0<confidence<1):
        raise ValueError('Experimental live AI requires an Ontario drawn circle with radius 20..250 metres')
    ai_path=root/'source'/'hospital_ai.py'
    if not ai_path.is_file():
        raise FileNotFoundError('Missing saved Ontario image downloader source. Run Notebook 08 setup once.')
    import sys
    spec=util.spec_from_file_location('hospital_ai_for_weak_inference',str(ai_path))
    ai=util.module_from_spec(spec);sys.modules[spec.name]=ai;spec.loader.exec_module(ai)
    direct=Transformer.from_crs('EPSG:4326','EPSG:3857',always_xy=True)
    inverse=Transformer.from_crs('EPSG:3857','EPSG:4326',always_xy=True)
    x,y=direct.transform(lon,lat)
    positions=[(0,0)] if rad<=130 else [(u,v) for u in (-250,0,250) for v in (-250,0,250)]
    model=YOLO(str(weights))
    result=[]
    with TemporaryDirectory(prefix='oss4008_weak_infer_') as directory:
        for idx,(dx,dy) in enumerate(positions):
            tile_lon,tile_lat=inverse.transform(x+dx/max(cos(radians(lat)),.01),
                                                y+dy/max(cos(radians(lat)),.01))
            png=Path(directory)/f'image{idx}.png';tif=Path(directory)/f'image{idx}.tif'
            ai.download_ontario_chip(tile_lat,tile_lon,png,tif)
            with rasterio.open(tif) as ds:
                image=Image.fromarray(ds.read((1,2,3)).transpose(1,2,0))
                to_wgs84=Transformer.from_crs(ds.crs,'EPSG:4326',always_xy=True)
                for detection in model.predict(source=image,conf=confidence,verbose=False):
                    for box in detection.boxes:
                        if int(box.cls[0])!=0:continue
                        x1,y1,x2,y2=map(float,box.xyxy[0].tolist())
                        if not (0<=x1<x2<=ds.width and 0<=y1<y2<=ds.height):continue
                        # Preserve the ACTUAL bounding rectangle, not just its centre point.
                        px,py=xy(ds.transform,(y1+y2)/2,(x1+x2)/2)
                        olon,olat=to_wgs84.transform(px,py)
                        a=sin(radians(olat-lat)/2)**2+cos(radians(lat))*cos(radians(olat))*sin(radians(olon-lon)/2)**2
                        if 6371008.8*2*asin(min(1,sqrt(a)))>rad:continue
                        ring=[]
                        for px_col,px_row in ((x1,y1),(x2,y1),(x2,y2),(x1,y2),(x1,y1)):
                            wx,wy=ds.transform*(px_col,px_row)
                            glon,glat=to_wgs84.transform(wx,wy)
                            ring.append([round(glon,8),round(glat,8)])
                        # Same physical-size screen as the city scan.  No height estimate is
                        # possible from this RGB image alone.
                        def _distance_m(pa,pb):
                            phi1,phi2=radians(pa[1]),radians(pb[1])
                            h=sin((phi2-phi1)/2)**2+cos(phi1)*cos(phi2)*sin(radians(pb[0]-pa[0])/2)**2
                            return 12742017.6*asin(min(1,sqrt(h)))
                        w_m=_distance_m(ring[0],ring[1]);h_m=_distance_m(ring[1],ring[2])
                        if min(w_m,h_m)<16 or w_m*h_m<750 or max(w_m,h_m)/max(.001,min(w_m,h_m))>6:
                            continue
                        result.append({'type':'Feature','geometry':{'type':'Polygon','coordinates':[ring]},
                                       'properties':{'confidence':float(box.conf[0]),
                                                     'method':'weak_yolo_geo_bbox',
                                                     'geometry_kind':'rectangle_approximation_not_exact_roof_outline',
                                                     'weights_sha256':report['weights_sha256'],
                                                     'warning':'EXPERIMENTAL roof rectangle; NOT verified hospital identity'}})
    # Remove duplicate overlapping chip detections within 12m.
    unique=[]
    for feature in sorted(result,key=lambda f:-f['properties']['confidence']):
        ring=feature['geometry']['coordinates'][0]
        lon2=(ring[0][0]+ring[2][0])/2; lat2=(ring[0][1]+ring[2][1])/2
        if all(hypot((lat2-(u['geometry']['coordinates'][0][0][1]+u['geometry']['coordinates'][0][2][1])/2)*111132,
                     (lon2-(u['geometry']['coordinates'][0][0][0]+u['geometry']['coordinates'][0][2][0])/2)*111320*cos(radians(lat2)))>12 for u in unique):
            unique.append(feature)
    return {'ok':True,'experimental':True,'features':unique,'count':len(unique),
            'image_chips':len(positions),'model_sha256':report['weights_sha256'],
            'note':'This is trained image inference but training labels were OSM/Overture/ODHF weak proxies; NOT verified hospital accuracy.'}
