#!/usr/bin/env bash
# Creates students/<firstname_lastname>/ for every line in students.txt.
# Line format:  Last, First [| github_username]
# If a GitHub username is given, CODEOWNERS lets that student own their folder.
# Safe to re-run: existing folders are left untouched; CODEOWNERS is regenerated.

set -euo pipefail
cd "$(dirname "$0")"

mkdir -p students
CODEOWNERS_FILE="CODEOWNERS"
{
  echo "# Auto-generated by setup_students.sh"
  echo "* @AdityaR28"
} > "$CODEOWNERS_FILE"

slug() {
  echo "$1" | iconv -f UTF-8 -t ASCII//TRANSLIT 2>/dev/null \
    | tr '[:upper:]' '[:lower:]' | tr -s ' ' '-' | tr -cd 'a-z0-9-'
}

while IFS= read -r line || [ -n "$line" ]; do
  line="$(echo "$line" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')"
  [ -z "$line" ] && continue
  case "$line" in \#*) continue ;; esac

  namepart="${line%%|*}"
  gh=""
  if [[ "$line" == *"|"* ]]; then
    gh="$(echo "${line#*|}" | tr -d '[:space:]@')"
  fi

  last="$(echo "${namepart%%,*}" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')"
  first="$(echo "${namepart#*,}" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')"
  folder="$(slug "$first")_$(slug "$last")"
  dir="students/$folder"

  if [ ! -d "$dir" ]; then
    mkdir -p "$dir/data" "$dir/code" "$dir/results"
    cat > "$dir/README.md" <<EOF
# $first $last: OSS4008A Project

**Project title:**
**Study area:**
**Data sources:**

## Progress log

| Week | Update |
|------|--------|
| 1    |        |
EOF
    echo "Data files go here (keep under 50 MB)." > "$dir/data/README.md"
    touch "$dir/code/.gitkeep" "$dir/results/.gitkeep"
    echo "Created $dir"
  else
    echo "Skipped $dir (already exists)"
  fi

  if [ -n "$gh" ]; then
    echo "/students/$folder/ @$gh @AdityaR28" >> "$CODEOWNERS_FILE"
  fi
done < students.txt

echo "Done. Review changes with: git status"
